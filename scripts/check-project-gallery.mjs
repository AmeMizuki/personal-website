// Run on /projects/ with a project containing at least two working images.
export async function checkProjectGallery() {
  const assert = (condition, message) => { if (!condition) throw new Error(message) }
  const tick = () => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve)))
  const pointer = (target, type, x, y) => target.dispatchEvent(new PointerEvent(type, { clientX: x, clientY: y, bubbles: true }))
  const gallery = [...document.querySelectorAll('.gallery')].find(element => element.querySelectorAll('.gallery__thumbnail').length >= 2)
  assert(gallery, 'Add at least two images to one project before running this check.')
  const thumbnails = gallery.querySelectorAll('.gallery__thumbnail')
  thumbnails[0].click()
  await tick()
  const main = gallery.querySelector('.gallery__main')
  assert(main, 'First image must load successfully.')
  const src = element => element.querySelector('img').getAttribute('src')
  const first = src(main)

  // Images fill their frames and are contained, never cropped.
  for (const image of [main.querySelector('img'), ...[...thumbnails].map(thumbnail => thumbnail.querySelector('img'))]) {
    assert(getComputedStyle(image).objectFit === 'contain', 'Images must use object-fit: contain.')
  }
  const mainImage = main.querySelector('img').getBoundingClientRect()
  assert(Math.abs(main.clientWidth - mainImage.width) < 1 && Math.abs(main.clientHeight - mainImage.height) < 1, 'Main image must fill its frame.')

  thumbnails[1].click()
  await tick()
  assert(src(main) === src(thumbnails[1]), 'Thumbnail must change main image.')
  assert(thumbnails[1].getAttribute('aria-pressed') === 'true', 'Selected thumbnail must expose selected state.')
  main.click()
  await tick()
  const dialog = gallery.querySelector('dialog')
  assert(dialog.open && dialog.matches(':modal'), 'Preview must open as a modal.')
  const viewport = dialog.getBoundingClientRect()
  assert(viewport.width === innerWidth && viewport.height === innerHeight, 'Preview must fill the viewport.')
  assert(getComputedStyle(dialog.querySelector('.gallery__full-image')).objectFit === 'contain', 'Preview image must be contained.')
  const stage = dialog.querySelector('.gallery__stage').getBoundingClientRect()
  const full = dialog.querySelector('.gallery__full-image').getBoundingClientRect()
  assert(Math.abs(stage.width - full.width) < 1 && Math.abs(stage.height - full.height) < 1, 'Preview image must fill the stage.')
  assert(src(dialog) === src(main), 'Modal must show selected image.')
  dialog.dispatchEvent(new KeyboardEvent('keydown', { key: 'ArrowLeft', bubbles: true }))
  await tick()
  assert(src(dialog) === first, 'ArrowLeft must select previous image.')
  dialog.querySelector('.gallery__navigation button:last-child').click()
  await tick()
  assert(src(dialog) === src(thumbnails[1]), 'Next control must change full preview.')

  const stageElement = dialog.querySelector('.gallery__stage')
  pointer(stageElement, 'pointerdown', 300, 200)
  pointer(stageElement, 'pointerup', 120, 205)
  await tick()
  assert(src(dialog) === src(thumbnails[Math.min(2, thumbnails.length - 1)]) || thumbnails.length === 2, 'Swiping left must show the next image.')
  pointer(stageElement, 'pointerdown', 120, 200)
  pointer(stageElement, 'pointerup', 300, 205)
  await tick()
  assert(src(dialog) === src(thumbnails[1]), 'Swiping right must show the previous image.')
  pointer(stageElement, 'pointerdown', 200, 200)
  pointer(stageElement, 'pointerup', 200, 360)
  await tick()
  assert(src(dialog) === src(thumbnails[1]), 'A vertical drag must not change the image.')

  dialog.querySelectorAll('.gallery__viewer-thumbnail')[0].click()
  await tick()
  assert(src(dialog) === first, 'Preview thumbnails must switch images.')
  dialog.querySelector('.gallery__toolbar button').click()
  await tick()
  assert(!dialog.open && document.activeElement === main, 'Closing must restore focus to main image.')
  thumbnails[0].click()
  await tick()
  console.log('Gallery fill, no-crop, thumbnail, modal, swipe, navigation and focus checks passed.')
  return { passed: true }
}
